#include "libft.h"
#include <stdlib.h>

void	ft_lstdelone(t_list *lst, void (*del)(void*))
{
	if (!del)
	{
		return ;
	}
	if (lst)
	{
		(*del)(lst->content);
		free(lst);
	}
}
